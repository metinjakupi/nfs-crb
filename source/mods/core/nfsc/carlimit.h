static void cl_rides_detect(void) {
    if (g_cl_wall != CL_WALL)
        return;
    int moved = 0, old = 0;
    for (uint32_t i = 0; i < 128u; ++i)
        moved += get_u32(CL_RIDES + 4u * i) != 0;
    for (uint32_t i = 0; i < 64u; ++i)
        old += get_u32(CL_RIDES_OLD + 4u * i) != 0;
    if (moved && !old) {
        g_cl_wall = 120u;
        log_line("core.nfsc: carlimit: this build registers rides in 128 entries (bodies patch): no 60-car wall");
    }
}

