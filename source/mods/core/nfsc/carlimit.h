/* carlimit.h - more than the game's 30 cars (Step B, 2026-11-05; logs/step-b-20261105/RESULT.md).
 * Included by nfsc.c after mp.h and crowd_test.h; carlimit_install after mp_install.
 *
 * WHAT HOLDS CARBON AT 30 (logs/vehicle-limit-20261105/findings.md, re-read in the recompiled listing):
 *   - fixed vectors of 30 (or 8) entries with their storage inline (+0x10), begin +4, capacity +8, count
 *     +0xc. A push grows through the method table (+0xc returns the fixed size) and reserve, which keeps the
 *     inline buffer, then writes begin[count] anyway: the 31st entry overwrites whatever follows;
 *   - PVehicle::Construct's gate 006d86f0: list 0's count + new cars > 30 (006d87f8), or the memory
 *     estimates over the budget, frees cars through the params' cache; its candidate vector (stack, 30 of
 *     0x18 bytes, `push 0x1e` at 006d8835) holds every car of the car list 0x00a9e728, so with more than 30
 *     cars it overflows the stack frame;
 *   - copies of list 0 into a 30-entry vector on the stack (00770340, 00770380 through 00767260 assign).
 *
 * WHAT THIS FILE DOES (all with hooks: code bytes cannot be patched in a recompiled game):
 *   1. LISTS. At the first frame (after the static constructors, before any car) every fixed list a car
 *      joins (CL_LISTS) gets a buffer of CL_CAP entries from guest_alloc: begin = it, capacity = CL_CAP.
 *      A push then finds room up to CL_CAP and never reserves (reserve(30) is a no-op once capacity is
 *      larger, and the alloc that returns the inline buffer is not called). The old inline storage is
 *      filled with CL_FILL and each buffer is followed by CL_GUARDS guard words; both are checked (every
 *      frame with RECOMP_CARLIMIT_CHECK=1, otherwise twice a second). A list found back on its inline
 *      buffer (begin changed by the game) is moved again while it still fits there.
 *   2. GATE. REPLACE 006d86f0. With list 0 + new cars <= 30 (and the car list as short) the original
 *      runs, unchanged. Above, it is not called (its stack vector would overflow): the same two tests are
 *      made here - the memory estimates (the loop at 006d8750..006d87bd: a new car whose model is a
 *      traffic or police model already present adds nothing; budget 007b11e0(flag), sum 006d41d0) and
 *      list 0 + new <= g_cl_max - and a car that does not fit is refused (AL = 0), never made room for.
 *      The game's own pending deletions (006c6190) are carried out first, as the original does. Rigid
 *      bodies keep their own gate (00761270: 64, shared with props); this one also refuses when fewer
 *      than CL_BODY_SPARE would be left for props.
 *   3. COPIES. BEFORE 00767260 (vector assign, thiscall (first, last)): into a vector whose storage is
 *      inline (or none yet) at most its fixed size (CL_INLINE_VT) is copied; into a moved list at most
 *      its capacity.
 *   4. SAFETY NET. Every vector push of the game's "grow, reserve, write" pattern (CL_PUSH_SITES: the
 *      reserve function and the return PC of its call; 147 sites in the 47 reserve functions of the vector
 *      template, whose code starts by comparing the argument with the capacity at +8) gets a call-site BEFORE
 *      hook: when the vector is full and the reserve will not grow it (count >= capacity >= asked), its
 *      count is lowered by one, so the push replaces its last entry instead of writing past the end. Each
 *      site logs the first time (and every 1000th) it does that, with the vector's table and capacity.
 *      Off with RECOMP_CARLIMIT_NET=0.
 *
 * g_cl_max (list 0's limit) is CL_MAX_DESKTOP or CL_MAX_PHONE (navigator.maxTouchPoints > 0), or
 * RECOMP_CARLIMIT=<n> (30 keeps the game's own limit; 0 turns this file off). mp.h reads it through
 * g_mp_list0_max; with the human list moved, g_mp_humans_max follows (HUMANS in mp.h).
 * The Cars pool (car memory budget) is raised at mod start to CL_POOL_DESKTOP / CL_POOL_PHONE KB, or
 * RECOMP_CARS_POOL=<KB>.
 */
