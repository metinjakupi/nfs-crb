#!/usr/bin/env python3
"""Generate the native player-only exclusion lookup from the shared relay policy."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
rows = json.loads((root / "tools/carbon-player-vehicles.json").read_text())["blocked"]
rows = sorted(rows, key=lambda row: row["key"])
assert len({row["key"] for row in rows}) == len(rows)
body = """/* Generated by tools/carbon-player-vehicles.py. Player access only. */
#ifndef CARBON_PLAYER_VEHICLES_H
#define CARBON_PLAYER_VEHICLES_H
#include <stdint.h>
static int player_vehicle_blocked(uint32_t key) {
  static const uint32_t keys[] = {
"""
body += "".join(f'    0x{row["key"]:08x}u, /* {row["name"]} */\n' for row in rows)
body += """  };
  uint32_t lo = 0, hi = (uint32_t)(sizeof keys / sizeof keys[0]);
  while (lo < hi) {
    const uint32_t mid = lo + (hi - lo) / 2;
    if (keys[mid] < key) lo = mid + 1; else hi = mid;
  }
  return lo < sizeof keys / sizeof keys[0] && keys[lo] == key;
}
#endif
"""
(root / "source/mods/core/nfsc/player_vehicles.h").write_text(body)
